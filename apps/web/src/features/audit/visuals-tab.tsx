import {
  ARTIFACT_PLACEMENTS,
  CATEGORIES,
  type Artifact,
  type ArtifactPlacement,
  type ArtifactType,
  type AuditDetail,
  type Category,
} from '@audivra/contracts'
import { ARTIFACT_TYPE_LABELS } from '@audivra/report-ui'
import { Link } from '@tanstack/react-router'
import { ChartColumn, FileText, Loader2, RotateCw, SearchX } from 'lucide-react'
import { useMemo, useState } from 'react'
import { AppArtifact } from '@/components/artifact-card'
import { Toolbar, ToolbarSpacer } from '@/components/page-header'
import { Panel } from '@/components/panel'
import { EmptyState, ErrorState, LoadingState, Notice } from '@/components/states'
import { Button, buttonVariants } from '@/components/ui/button'
import { Select } from '@/components/ui/select'
import { isFinished, isTerminal } from '@/lib/queries'
import { cn } from '@/lib/utils'
import { usePresentMutation } from './use-present'

type All = 'all'

const PLACEMENT_LABEL: Record<ArtifactPlacement, string> = {
  overview: 'Overview',
  report: 'Client report',
  appendix: 'Appendix',
}

const PLACEMENT_HINT: Record<ArtifactPlacement, string> = {
  overview: 'Featured at the top of the overview and the report',
  report: 'Shown in the main body of the client report',
  appendix: 'Supporting detail for the technical appendix',
}

/** Types that read better at half width; everything else spans the full row. */
const COMPACT_TYPES: ReadonlySet<ArtifactType> = new Set([
  'metric',
  'comparison_bar',
  'bar_chart',
  'stacked_bar',
  'donut',
  'trend_metric',
  'tech_map',
])

/**
 * Compact visuals pair up two per row; a compact visual without a compact neighbour (and every wide
 * type) takes the full row, so no card is left stranded at half width.
 */
function fullWidthRefs(items: Artifact[]): Set<string> {
  const full = new Set<string>()
  let run: Artifact[] = []
  const flush = () => {
    if (run.length % 2 === 1) full.add(run[run.length - 1]!.ref)
    run = []
  }
  for (const item of items) {
    if (COMPACT_TYPES.has(item.type)) run.push(item)
    else {
      flush()
      full.add(item.ref)
    }
  }
  flush()
  return full
}

function VisualCard({ artifact, auditId, full }: { artifact: Artifact; auditId: string; full: boolean }) {
  return (
    <div className={cn('flex min-w-0 flex-col gap-1', full && 'xl:col-span-2')}>
      <AppArtifact artifact={artifact} auditId={auditId} />
      <p className="px-1 text-2xs text-subtle">
        {ARTIFACT_TYPE_LABELS[artifact.type]} ·{' '}
        {artifact.createdBy === 'planner'
          ? 'Selected by the artifact planner; data resolved by Audivra'
          : 'Generated by Audivra from audit data'}
      </p>
    </div>
  )
}

function GenerateAction({ audit, label }: { audit: AuditDetail; label: string }) {
  const present = usePresentMutation(audit.id)
  const failed = audit.steps.find((s) => s.stage === 'presenting')?.status === 'failed'
  return (
    <Button size="sm" onClick={() => present.mutate()} disabled={present.isPending}>
      {present.isPending ? <Loader2 className="animate-spin" /> : failed ? <RotateCw /> : <ChartColumn />}
      {failed ? 'Try again' : label}
    </Button>
  )
}

export function VisualsTab({
  audit,
  visuals,
  isLoading,
  error,
  onRetry,
  presenting,
}: {
  audit: AuditDetail
  visuals: Artifact[]
  isLoading: boolean
  error: unknown
  onRetry: () => void
  presenting: boolean
}) {
  const [placement, setPlacement] = useState<ArtifactPlacement | All>('all')
  const [category, setCategory] = useState<Category | All>('all')
  const [type, setType] = useState<ArtifactType | All>('all')

  const filtered = useMemo(
    () =>
      visuals.filter(
        (a) =>
          (placement === 'all' || a.placement === placement) &&
          (category === 'all' || a.category === category) &&
          (type === 'all' || a.type === type),
      ),
    [visuals, placement, category, type],
  )
  const presentTypes = [...new Set(visuals.map((a) => a.type))]
  const presentCategories = CATEGORIES.filter((c) => visuals.some((a) => a.category === c))
  const filtering = placement !== 'all' || category !== 'all' || type !== 'all'
  const finished = isFinished(audit.status)
  const canGenerate = finished && audit.aiEnabled && audit.findingCount > 0 && !presenting

  if (error) {
    return (
      <Panel>
        <ErrorState title="Could not load visuals" error={error} onRetry={onRetry} />
      </Panel>
    )
  }
  if (isLoading) {
    return (
      <Panel>
        <LoadingState rows={6} />
      </Panel>
    )
  }
  if (visuals.length === 0) {
    return (
      <Panel>
        <EmptyState
          icon={presenting ? Loader2 : ChartColumn}
          title={
            presenting
              ? 'Generating visuals…'
              : !isTerminal(audit.status)
                ? 'Visuals are created after the findings are final'
                : 'No visuals for this audit'
          }
          description={
            presenting
              ? 'The artifact planner chooses what to show; Audivra resolves every value from recorded evidence.'
              : !isTerminal(audit.status)
                ? 'The artifact planner picks which charts, tables and annotated screenshots explain the findings. Every value comes from recorded evidence.'
                : canGenerate
                  ? 'Generate them from the stored findings and evidence. The site is not crawled again.'
                  : 'Visuals need a finished audit with findings.'
          }
          action={canGenerate ? <GenerateAction audit={audit} label="Generate visuals" /> : null}
        />
      </Panel>
    )
  }

  const groups = ARTIFACT_PLACEMENTS.map((p) => {
    const items = filtered.filter((a) => a.placement === p).sort((a, b) => a.priority - b.priority)
    return { placement: p, items, full: fullWidthRefs(items) }
  }).filter((group) => group.items.length)
  const presentFailed = audit.steps.find((s) => s.stage === 'presenting')?.status === 'failed'

  return (
    <div className="flex flex-col gap-3">
      {presenting ? (
        <Notice icon={Loader2} iconClassName="animate-spin" title="Regenerating visuals">
          The list refreshes when the artifact planner and report composer finish.
        </Notice>
      ) : canGenerate && presentFailed ? (
        <Notice
          tone="warning"
          icon={ChartColumn}
          title="Visual report generation failed"
          action={<GenerateAction audit={audit} label="Generate visual report" />}
        >
          Showing the visuals that exist. Findings and evidence are unaffected.
        </Notice>
      ) : canGenerate && !audit.reportPlan ? (
        <Notice
          icon={ChartColumn}
          title="Basic visuals only"
          action={<GenerateAction audit={audit} label="Generate visual report" />}
        >
          These were built from measurements. The artifact planner can add finding-specific visuals and annotated
          screenshots.
        </Notice>
      ) : null}
      <Toolbar>
        <Select
          label="Placement"
          value={placement}
          onValueChange={setPlacement}
          options={[
            { value: 'all', label: 'All' },
            ...ARTIFACT_PLACEMENTS.filter((p) => visuals.some((a) => a.placement === p)).map((p) => ({
              value: p,
              label: PLACEMENT_LABEL[p],
            })),
          ]}
        />
        {presentCategories.length ? (
          <Select
            label="Category"
            value={category}
            onValueChange={setCategory}
            options={[{ value: 'all', label: 'All' }, ...presentCategories.map((c) => ({ value: c, label: c }))]}
          />
        ) : null}
        <Select
          label="Type"
          value={type}
          onValueChange={setType}
          options={[
            { value: 'all', label: 'All' },
            ...presentTypes.map((t) => ({ value: t, label: ARTIFACT_TYPE_LABELS[t] })),
          ]}
        />
        {filtering ? (
          <Button
            variant="ghost"
            size="sm"
            onClick={() => {
              setPlacement('all')
              setCategory('all')
              setType('all')
            }}
          >
            Clear
          </Button>
        ) : null}
        <ToolbarSpacer />
        <span className="text-xs text-muted tabular-nums">
          {filtering ? `${filtered.length} of ${visuals.length}` : visuals.length} visuals
        </span>
        {finished ? (
          <Link
            to="/audits/$auditId/report"
            params={{ auditId: audit.id }}
            className={buttonVariants({ size: 'sm' })}
          >
            <FileText />
            Open report
          </Link>
        ) : null}
      </Toolbar>
      {groups.length === 0 ? (
        <Panel>
          <EmptyState icon={SearchX} compact title="No visuals match these filters" />
        </Panel>
      ) : (
        groups.map((group) => (
          <section key={group.placement} aria-labelledby={`visuals-${group.placement}`} className="flex flex-col gap-2">
            <div className="flex items-baseline gap-2 px-1 pt-1">
              <h2 id={`visuals-${group.placement}`} className="text-sm font-semibold text-foreground">
                {PLACEMENT_LABEL[group.placement]}
              </h2>
              <span className="text-xs text-subtle">{PLACEMENT_HINT[group.placement]}</span>
            </div>
            <div className="grid grid-cols-1 gap-3 xl:grid-cols-2">
              {group.items.map((artifact) => (
                <VisualCard
                  key={artifact.id}
                  artifact={artifact}
                  auditId={audit.id}
                  full={group.full.has(artifact.ref)}
                />
              ))}
            </div>
          </section>
        ))
      )}
    </div>
  )
}
